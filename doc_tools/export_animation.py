"""Export a documentation animation as a self-contained, offline HTML file."""

import argparse
import base64
from html import escape
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]


def render(name):
    """Bundle the shared player, styles and one registered scene."""
    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", name):
        raise ValueError("Animation names must be lowercase words separated by hyphens")
    assets = ROOT / "doc" / "assets"
    scene = (assets / "animations" / f"{name}.js").read_text()
    if name == "tip-cutting-before-purge":
        scene = (assets / "animations" / "tip-cutting-purge.js").read_text() + "\n" + scene
    player = (assets / "javascripts" / "hh-animations.js").read_text()
    styles = (assets / "stylesheets" / "hh-animations.css").read_text()
    logo = base64.b64encode((assets / "images" / "favicon.png").read_bytes()).decode("ascii")
    styles = styles.replace("../images/favicon.png", "data:image/png;base64," + logo)
    # Escape closing tags in source so they cannot terminate the inline elements.
    scripts = (player + "\n" + scene).replace("</script", r"<\/script")
    styles = styles.replace("</style", r"<\/style")
    title = escape(name.replace("-", " ").capitalize())
    return f'''<!doctype html>
<!-- Generated by doc_tools.export_animation; edit the shared assets instead. -->
<html lang="en" data-md-color-scheme="default">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title} | Happy Hare</title>
<style>
body {{ margin: 0 auto; padding: 16px; max-width: 850px; background: #fff; color: #20344b; color-scheme: light; }}
html[data-md-color-scheme="slate"] body {{ background: #202936; color: #e3eaf2; color-scheme: dark; }}
{styles}
</style>
</head>
<body>
<main aria-label="{title}">
<div data-hh-animation="{name}"><p>Enable JavaScript to play this animation.</p></div>
</main>
<script>{scripts}</script>
</body>
</html>
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("name", help="Scene filename without .js")
    parser.add_argument("output", type=Path, help="Destination HTML file")
    args = parser.parse_args()
    result = render(args.name)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(result)
    print(args.output)


if __name__ == "__main__":
    main()
